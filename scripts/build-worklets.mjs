// Builds public/worklets/dx7-poly.js: the DX7 engine from @audio/synth-dx7 followed by
// our processor (src/worklets/dx7-processor.js), as one plain script. Audio worklets load
// a single file, and not every browser supports imports inside them.
// Runs before `npm run dev` and `npm run build`. The output is generated, not committed.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("@audio/synth-dx7/package.json"));
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;

// Drop the module syntax so the two files can share one script scope.
const strip = (code) =>
  code
    .replace(/^import .*$/gm, "")
    .replace(/^export \{[^}]*\} from .*$/gm, "")
    .replace(/^export default function/gm, "function")
    .replace(/^export (class|function|const|let)/gm, "$1");

const notice = readFileSync(join(pkgDir, "NOTICE"), "utf8").trim();
const out = [
  `/*\n * Generated by scripts/build-worklets.mjs. Do not edit.\n *\n * FM engine: @audio/synth-dx7 ${version}, Apache License 2.0.\n * ${notice.replace(/\n/g, "\n * ")}\n * Full licence: /vendor/synth-dx7/LICENSE\n */`,
  "(() => {",
  strip(readFileSync(join(pkgDir, "sysex.js"), "utf8")),
  strip(readFileSync(join(pkgDir, "dx7.js"), "utf8")),
  readFileSync("src/worklets/dx7-processor.js", "utf8"),
  "})();",
].join("\n");

mkdirSync("public/worklets", { recursive: true });
writeFileSync("public/worklets/dx7-poly.js", out);
mkdirSync("public/vendor/synth-dx7", { recursive: true });
for (const file of ["LICENSE", "NOTICE"]) {
  writeFileSync(join("public/vendor/synth-dx7", file), readFileSync(join(pkgDir, file)));
}
console.log(`[worklets] Built public/worklets/dx7-poly.js with @audio/synth-dx7 ${version}.`);
